"""Writes THIRD_PARTY_LICENSES.md: every crate LiveReplay (app, server, web viewer) is built from,
with its licence and the licence / notice files shipped in the crate. Run after dependency changes:
    python scripts/third_party_licenses.py
"""
import json, os, subprocess, hashlib, collections

meta = json.loads(subprocess.check_output(["cargo", "metadata", "--format-version", "1"], text=True))
members = set(meta["workspace_members"])
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
pkgs = {p["id"]: p for p in meta["packages"]}

# Everything reachable from the workspace members through normal/build dependencies.
seen, stack = set(), list(members)
while stack:
    i = stack.pop()
    if i in seen:
        continue
    seen.add(i)
    for d in nodes[i]["deps"]:
        if any(k["kind"] in (None, "build") for k in d["dep_kinds"]):
            stack.append(d["pkg"])

used = sorted((pkgs[i] for i in seen if i not in members), key=lambda p: (p["name"].lower(), p["version"]))
texts = collections.OrderedDict()  # hash -> text
entries = []
for p in used:
    root = os.path.dirname(p["manifest_path"])
    files = []
    for f in sorted(os.listdir(root)):
        up = f.upper()
        if up.startswith(("LICENSE", "LICENCE", "COPYING", "NOTICE", "COPYRIGHT")) and os.path.isfile(os.path.join(root, f)):
            t = open(os.path.join(root, f), encoding="utf-8", errors="replace").read().strip()
            h = hashlib.sha1(t.encode()).hexdigest()[:10]
            texts.setdefault(h, t)
            files.append((f, h))
    entries.append((p["name"], p["version"], p.get("license") or p.get("license_file") or "unknown", p.get("repository") or "", files))

out = ["# Third-party licences", "",
       "LiveReplay is licensed under CC BY-NC-SA 4.0 (see LICENSE). It is built with the open-source libraries below,",
       "each under its own licence. Generated by `scripts/third_party_licenses.py`.", "",
       "| Crate | Version | Licence | Licence files |", "|---|---|---|---|"]
for name, ver, lic, repo, files in entries:
    link = f"[{name}]({repo})" if repo else name
    out.append(f"| {link} | {ver} | {lic} | {', '.join(f'[{f}](#t-{h})' for f, h in files) or '-'} |")
out += ["", "## Licence texts", ""]
for h, t in texts.items():
    users = [f"{n} {v}" for n, v, _, _, fs in entries if any(x[1] == h for x in fs)]
    out += [f'<a id="t-{h}"></a>', f"### Used by: {', '.join(users)}", "", "```text", t.replace("```", "'''"), "```", ""]
open("THIRD_PARTY_LICENSES.md", "w", encoding="utf-8").write("\n".join(out))
print(len(entries), "crates,", len(texts), "distinct licence texts")
